DECLARE
  v_summary TEXT;
  v_website TEXT;
  v_queue_id UUID;
  v_status TEXT;
  v_eligible BOOLEAN;
BEGIN
  IF auth.role() <> 'service_role' THEN
    RAISE EXCEPTION 'service_role required';
  END IF;


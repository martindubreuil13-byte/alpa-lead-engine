      OR NEW.website_snapshot IS NOT NULL
      OR NEW.business_signals IS NOT NULL
      OR NEW.commercial_profile IS NOT NULL
    THEN
      RAISE EXCEPTION 'a lead cannot be created with research state or results'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;

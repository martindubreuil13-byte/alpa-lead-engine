-- ALPA billing TEST environment: foundational schema, reconstructed READ-ONLY from the production catalog on 2026-10-15.
--
--   * Structure only: tables, columns, defaults, constraints, indexes, functions, triggers, row-level-security policies and grants.
--     No row of data was copied (no customers, leads, subscriptions, guest trials, credentials or auth records).
--   * Apply it to an EMPTY Supabase TEST project (SQL editor, as the postgres role). Never to production.
--   * Supabase-managed pieces are NOT recreated and must already exist in the project: schema `auth` (auth.users, auth.uid(), auth.role()),
--     the roles anon / authenticated / service_role, and the usual extensions. pg_cron / pg_net / vault are not needed by billing tests
--     (the one function that uses them, configure_alpa_ci_worker_schedule, is created but never called).
--   * The grants section first resets every privilege on the public schema, because a new Supabase project hands anon and
--     authenticated broad default privileges that production does not have.
--   * MAINTAIN is a PostgreSQL 17 privilege (production and new Supabase projects are on 17). On an older engine remove it from the grants.
--   * Generated by hand from catalog queries; verified by scripts/test-env/verify-schema.mjs (empty-database load + catalog fingerprint).
